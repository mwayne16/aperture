import { Aperture, FlaskConical, Monitor, Moon, SlidersHorizontal, Sun } from 'lucide-react';
import type { ReactNode } from 'react';
import { useUiStore } from '../../app/uiStore';
import { Badge, type BadgeTone } from '../../components/ui/Badge';
import { Button } from '../../components/ui/Button';
import { SegmentedControl, type SegmentedOption } from '../../components/ui/SegmentedControl';
import { StatusDot } from '../../components/ui/StatusDot';
import { Tooltip } from '../../components/ui/Tooltip';
import { useTheme, type ThemePreference } from '../../components/ui/theme';
import { useConnection, useConnectionStore } from '../../data/connectionStore';
import { formatClock } from '../../lib/format';
import { SymbolSearch } from '../market/SymbolSearch';
import { connectionDetails, describeConnection } from './connectionStatus';
import { MARKET_SESSION_LABELS, marketSession, type MarketSession } from './marketSession';
import { useFeedStatus } from './useFeedStatus';
import { useNow } from './useNow';
import './shell.css';

/**
 * Top bar content: brand, global search, the simulated-data marker, connection status, the New York
 * market clock, the theme control and the simulation controls button. One 40px row; below ~1100px
 * the lower-priority labels collapse to icons but keep their accessible names.
 */
export function TopBar() {
  return (
    <div className="shell-topbar">
      <h1 className="shell-brand">
        <Aperture className="shell-brand__mark" aria-hidden="true" />
        <span className="shell-collapse">Aperture</span>
      </h1>
      <SimulatedMarker />
      <div className="shell-topbar__search">
        <SymbolSearch variant="global" />
      </div>
      <div className="shell-topbar__spacer" />
      <ConnectionIndicator />
      <MarketClock />
      <ThemeControl />
      <SimulationControlsButton />
    </div>
  );
}

function SimulatedMarker() {
  const simulated = useConnectionStore((s) => s.connection.simulated);
  if (!simulated) return null;
  return (
    <Tooltip content="Prices are generated by the prototype. No real market data is used." side="bottom">
      {/* ** Focusable so keyboard users can open the explanation too; it is the app's key disclaimer. */}
      <span className="shell-simulated" tabIndex={0}>
        <Badge tone="warning">
          <FlaskConical aria-hidden="true" />
          Simulated<span className="shell-collapse"> data</span>
        </Badge>
      </span>
    </Tooltip>
  );
}

function ConnectionIndicator() {
  const connection = useConnection();
  const { freshness } = useFeedStatus();
  const view = describeConnection(connection, freshness);
  return (
    // The tooltip repeats details the status bar shows, so a hover-only trigger loses nothing.
    <Tooltip content={<ConnectionTooltip />} side="bottom">
      <span className="shell-connection" role="status">
        <StatusDot tone={view.tone} pulse={view.pulse} />
        <span className="shell-connection__label shell-collapse-narrow">{view.label}</span>
        {view.dataNote && (
          <Badge tone="warning" size="sm">
            {view.dataNote.label}
          </Badge>
        )}
      </span>
    </Tooltip>
  );
}

function ConnectionTooltip() {
  const connection = useConnection();
  const now = useNow();
  return (
    <span className="shell-tooltip-lines">
      {connectionDetails(connection, now).map((line) => (
        <span key={line}>{line}</span>
      ))}
    </span>
  );
}

const SESSION_TONES: Readonly<Record<MarketSession, BadgeTone>> = {
  'pre-market': 'accent',
  open: 'gain',
  'after-hours': 'accent',
  closed: 'muted',
};

const SESSION_HOURS =
  'New York time. Weekdays: pre-market 04:00–09:30, open 09:30–16:00, after hours 16:00–20:00. ' +
  'Exchange holidays and early closes are not shown.';

function MarketClock() {
  const now = useNow();
  const session = marketSession(now);
  return (
    <Tooltip content={SESSION_HOURS} side="bottom">
      <span className="shell-clock">
        <time className="shell-clock__time num" dateTime={new Date(now).toISOString()}>
          {formatClock(now)}
          <span className="shell-clock__zone"> ET</span>
        </time>
        <Badge tone={SESSION_TONES[session]} size="sm">
          {MARKET_SESSION_LABELS[session]}
        </Badge>
      </span>
    </Tooltip>
  );
}

const THEME_OPTIONS: SegmentedOption<ThemePreference>[] = [
  { value: 'system', label: <ThemeIcon icon={<Monitor />} name="System" />, title: 'Match the system theme' },
  { value: 'dark', label: <ThemeIcon icon={<Moon />} name="Dark" />, title: 'Dark theme' },
  { value: 'light', label: <ThemeIcon icon={<Sun />} name="Light" />, title: 'Light theme' },
];

function ThemeIcon({ icon, name }: { icon: ReactNode; name: string }) {
  return (
    <>
      <span className="shell-theme__icon" aria-hidden="true">
        {icon}
      </span>
      <span className="visually-hidden">{name}</span>
    </>
  );
}

function ThemeControl() {
  const { preference, setPreference } = useTheme();
  return (
    <SegmentedControl size="sm" aria-label="Theme" options={THEME_OPTIONS} value={preference} onChange={setPreference} />
  );
}

function SimulationControlsButton() {
  return (
    <Tooltip content="Simulation controls" side="bottom">
      <Button
        variant="ghost"
        size="sm"
        icon={<SlidersHorizontal />}
        aria-label="Simulation controls"
        aria-haspopup="dialog"
        className="shell-topbar__controls"
        onClick={() => {
          useUiStore.getState().setPrototypeControlsOpen(true);
        }}
      >
        <span className="shell-collapse">Simulation</span>
      </Button>
    </Tooltip>
  );
}
