import { act, render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { StrictMode } from 'react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { useUiStore } from '../../app/uiStore';
import { resetShellStores, quote, setConnection, setQuotes, watch } from './testUtils';
import { TopBar } from './TopBar';

beforeEach(() => {
  resetShellStores();
});

afterEach(() => {
  vi.useRealTimers();
  resetShellStores();
});

const connectionStatus = () => screen.getByRole('status');

describe('TopBar', () => {
  it('shows where the user is and hosts the global symbol search', () => {
    render(<TopBar />);
    expect(screen.getByRole('navigation', { name: 'Breadcrumb' })).toHaveTextContent('Dashboard');
    expect(screen.getByRole('combobox', { name: 'Search symbols' })).toBeInTheDocument();
  });

  it('marks the data as simulated and explains why on keyboard focus', async () => {
    const user = userEvent.setup();
    render(<TopBar />);
    const marker = screen.getByText('Simulated', { exact: false }).closest('[tabindex]');
    expect(marker).toHaveTextContent('Simulated data');
    await user.tab();
    expect(marker).toHaveFocus();
    expect(screen.getByRole('tooltip')).toHaveTextContent(
      'Prices are generated by the prototype. No real market data is used.',
    );
    expect(marker).toHaveAccessibleDescription(
      'Prices are generated by the prototype. No real market data is used.',
    );
  });

  it('labels every connection state, including the reconnect attempt', () => {
    render(<TopBar />);
    setConnection({ state: 'connecting' });
    expect(connectionStatus()).toHaveTextContent('Connecting…');
    setConnection({ state: 'connected', lastMessageAt: Date.now() });
    expect(connectionStatus()).toHaveTextContent('Connected');
    setConnection({ state: 'reconnecting', reconnectAttempt: 2, nextRetryAt: Date.now() + 2000 });
    expect(connectionStatus()).toHaveTextContent('Reconnecting (attempt 2)');
    setConnection({ state: 'disconnected', error: 'Simulated outage: the feed is unreachable.' });
    expect(connectionStatus()).toHaveTextContent('Disconnected');
  });

  it('flags delayed quotes on the subscribed symbols', () => {
    render(<TopBar />);
    watch(['AAPL', 'MSFT']);
    setConnection({ state: 'connected' });
    setQuotes([quote('AAPL', 'delayed'), quote('MSFT', 'delayed')]);
    expect(within(connectionStatus()).getByText('Delayed')).toBeInTheDocument();

    setQuotes([quote('AAPL', 'live'), quote('MSFT', 'live')]);
    expect(within(connectionStatus()).queryByText('Delayed')).not.toBeInTheDocument();
  });

  it('ignores quotes for symbols the app no longer subscribes to', () => {
    render(<TopBar />);
    setConnection({ state: 'connected' });
    // TSLA kept its last live status after it was unsubscribed; the watched symbol went stale.
    setQuotes([quote('TSLA', 'live'), quote('AAPL', 'stale')]);
    watch(['AAPL']);
    expect(within(connectionStatus()).getByText('Stale')).toBeInTheDocument();
  });

  it('runs a New York clock with the market session', () => {
    vi.useFakeTimers({ now: Date.parse('2026-10-28T09:29:58-04:00') });
    render(<TopBar />);
    expect(screen.getByText('09:29:58', { exact: false })).toHaveTextContent('09:29:58 ET');
    expect(screen.getByText('Pre-market')).toBeInTheDocument();
    act(() => {
      vi.advanceTimersByTime(2000);
    });
    expect(screen.getByText('09:30:00', { exact: false })).toHaveTextContent('09:30:00 ET');
    expect(screen.getByText('Open')).toBeInTheDocument();
  });

  it('reads closed on a weekend', () => {
    vi.useFakeTimers({ now: Date.parse('2026-10-31T11:00:00-04:00') });
    render(<TopBar />);
    expect(screen.getByText('Closed')).toBeInTheDocument();
  });

  it('switches the theme and applies it to the document', async () => {
    const user = userEvent.setup();
    render(<TopBar />);
    const theme = screen.getByRole('radiogroup', { name: 'Theme' });
    await user.click(within(theme).getByRole('radio', { name: 'Light' }));
    expect(document.documentElement.dataset.theme).toBe('light');
    expect(within(theme).getByRole('radio', { name: 'Light' })).toHaveAttribute('aria-checked', 'true');
    await user.click(within(theme).getByRole('radio', { name: 'Dark' }));
    expect(document.documentElement.dataset.theme).toBe('dark');
    await user.click(within(theme).getByRole('radio', { name: 'System' }));
    expect(within(theme).getByRole('radio', { name: 'System' })).toHaveAttribute('aria-checked', 'true');
  });

  it('opens the simulation controls', async () => {
    const user = userEvent.setup();
    render(<TopBar />);
    await user.click(screen.getByRole('button', { name: 'Simulation controls' }));
    expect(useUiStore.getState().prototypeControlsOpen).toBe(true);
  });

  it('mounts cleanly under StrictMode and leaves no clock timer behind', () => {
    vi.useFakeTimers();
    const { unmount } = render(
      <StrictMode>
        <TopBar />
      </StrictMode>,
    );
    expect(screen.getAllByRole('navigation', { name: 'Breadcrumb' })).toHaveLength(1);
    unmount();
    expect(vi.getTimerCount()).toBe(0);
  });
});
